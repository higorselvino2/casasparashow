const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const {pathToFileURL}=require('node:url');
const {chromium}=require('playwright');
const root=path.resolve(__dirname,'..');
let browser;
(async()=>{
  browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8768/',{waitUntil:'networkidle'});
  await page.locator('[data-artist-photo]').first().waitFor();
  const expected=await page.evaluate(()=>[...new Set([...CASAS,...CONSULTAS].flatMap(v=>v.artists?.names||[]))]);
  const actual=await page.locator('[data-artist-photo]').evaluateAll(els=>[...new Set(els.map(e=>e.dataset.artistPhoto))]);
  assert.deepEqual(actual.sort(),expected.sort());
  assert.equal(actual.length,22);
  await page.locator('.artist-image-frame img').evaluateAll(imgs=>Promise.all(imgs.map(img=>{img.loading='eager';return img.decode();})));
  const images=await page.locator('.artist-image-frame img').evaluateAll(imgs=>imgs.map(i=>({name:i.alt,width:i.naturalWidth,height:i.naturalHeight})));
  assert(images.every(i=>i.width>=300&&i.height>=300),JSON.stringify(images));
  assert.equal(await page.locator('.artist-tile figcaption>a').count(),images.length);
  for(const size of [{width:360,height:800},{width:390,height:844},{width:768,height:1000},{width:1440,height:1000}]){
    await page.setViewportSize(size);
    const metrics=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,width:innerWidth,frames:[...document.querySelectorAll('.artist-image-frame')].map(e=>({w:e.getBoundingClientRect().width,h:e.getBoundingClientRect().height}))}));
    assert(metrics.scroll<=metrics.width,'Overflow '+JSON.stringify(size));
    assert(metrics.frames.every(f=>f.w>=120&&f.h>=160),'Photographs too small '+JSON.stringify({size,metrics}));
    if(size.width<=390)assert(metrics.frames.every(f=>f.w>=260&&f.h>=200),'Mobile photographs must use the full column');
  }
  const first=page.locator('#casa-palacio [data-artist-photo]').first();
  await first.click();
  assert.equal(await page.locator('#artistPhotoDialog').isVisible(),true);
  assert.equal(await page.locator('#artistPhotoTitle').textContent(),'Marcos & Belutti');
  await page.locator('#artistPhotoLarge').evaluate(img=>img.decode());
  assert((await page.locator('#artistPhotoCredit').textContent()).includes('Som Livre'));
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#artistPhotoDialog').isVisible(),false);
  assert.equal(await first.evaluate(el=>el===document.activeElement),true);
  fs.mkdirSync(path.join(root,'relatorios'),{recursive:true});
  await page.locator('#casa-palacio .artist-history').screenshot({path:path.join(root,'relatorios','artistas-desktop.png')});
  await page.setViewportSize({width:390,height:844});
  await page.locator('#casa-palacio .artist-history').screenshot({path:path.join(root,'relatorios','artistas-mobile.png')});
  await first.click();
  await page.screenshot({path:path.join(root,'relatorios','artista-ampliado-mobile.png')});
  const bounds=await page.locator('#artistPhotoDialog').boundingBox();
  assert(bounds.x>=0&&bounds.x+bounds.width<=390&&bounds.height<=844);
  await page.locator('#closeArtistPhoto').click();
  assert.equal(await page.locator('#artistPhotoDialog').isVisible(),false);
  await page.goto(pathToFileURL(path.join(root,'index.html')).href,{waitUntil:'load'});
  assert.equal(await page.locator('[data-artist-photo]').count(),images.length);
  await page.locator('#casa-nova [data-artist-photo]').click();
  assert.equal(await page.locator('#artistPhotoTitle').textContent(),'João Bosco & Gabriel');
  await page.locator('#artistPhotoLarge').evaluate(img=>img.decode());
  assert.equal(errors.length,0,errors.join('\n'));
  console.log('OK:',images.length,'cartões com foto;',actual.length,'artistas; imagens >=300px; créditos; 4 larguras; ampliação; fechamento por botão e Escape; foco restaurado; arquivo local; sem erros de JavaScript.');
})().catch(e=>{console.error(e);process.exitCode=1;}).finally(()=>browser?.close());
